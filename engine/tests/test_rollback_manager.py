"""
test_rollback_manager.py — Test suite for the Atomic Snapshot & Rollback Engine.
Validates state capture, checksum verification, destructive state restoration,
and safety pre-rollback recovery points.
"""

import sys
from pathlib import Path

# Add engine directory to sys.path
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from app.core.rollback_manager import RollbackManager
from app.tools.file_manager import WORKSPACE_DIR, delete_file, read_file, write_file


def test_snapshot_creation_and_listing():
    """Verify that creating a snapshot writes manifest and updates index cleanly."""
    # Ensure clean test file exists
    test_file = "test_artifact.txt"
    write_file(test_file, "Initial state for snapshot test")

    snapshot = RollbackManager.create_snapshot(
        trigger="unit_test",
        iteration=1,
        label="Test Baseline Snapshot",
    )

    assert snapshot is not None
    assert "snapshot_id" in snapshot
    assert snapshot["trigger"] == "unit_test"
    assert snapshot["iteration"] == 1
    assert test_file in snapshot["files"]

    # Verify listing
    snapshots = RollbackManager.list_snapshots(limit=10)
    assert len(snapshots) > 0
    assert snapshots[0]["snapshot_id"] == snapshot["snapshot_id"]

    # Clean up test file
    delete_file(test_file)


def test_atomic_rollback_lifecycle():
    """
    Test full rollback lifecycle:
    1. Write file A (v1) and file B.
    2. Capture Baseline Snapshot.
    3. Modify file A (v2), delete file B, and create rogue file C.
    4. Execute rollback to Baseline Snapshot.
    5. Verify:
       - File A is restored to v1.
       - File B is restored.
       - Rogue file C is deleted.
       - A safety pre-rollback recovery snapshot was created.
    """
    # Step 1: Write initial files
    file_a = "sandbox_module_a.py"
    file_b = "sandbox_module_b.py"
    rogue_c = "sandbox_rogue_c.py"

    write_file(file_a, 'print("Module A version 1")\n')
    write_file(file_b, 'print("Module B active")\n')

    # Step 2: Capture baseline snapshot
    baseline_snap = RollbackManager.create_snapshot(
        trigger="lifecycle_test",
        label="Baseline State",
    )
    snap_id = baseline_snap["snapshot_id"]

    # Step 3: Perform mutations (simulating agentic loop modifications)
    write_file(file_a, 'print("Module A mutated version 2 - BROKEN")\n')
    delete_file(file_b)
    write_file(rogue_c, 'print("Unintended rogue file generated by agent")\n')

    # Verify mutations took effect
    assert "BROKEN" in read_file(file_a)
    assert (WORKSPACE_DIR / rogue_c).is_file()
    assert not (WORKSPACE_DIR / file_b).is_file()

    # Step 4: Execute Rollback
    result = RollbackManager.rollback_to_snapshot(snap_id)
    assert result["success"] is True
    assert result["snapshot_id"] == snap_id
    assert file_a in result["files_restored"]
    assert file_b in result["files_restored"]
    assert rogue_c in result["files_deleted"]
    assert "safety_snapshot_id" in result

    # Step 5: Verify workspace state is completely restored
    assert read_file(file_a) == 'print("Module A version 1")\n'
    assert read_file(file_b) == 'print("Module B active")\n'
    assert not (WORKSPACE_DIR / rogue_c).exists()

    # Cleanup test files
    delete_file(file_a)
    delete_file(file_b)


if __name__ == "__main__":
    test_snapshot_creation_and_listing()
    test_atomic_rollback_lifecycle()
    print("All Atomic Snapshot & Rollback tests passed successfully!")
